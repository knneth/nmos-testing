def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR,
        help=f"Test streams directory (default: {DEFAULT_OUTPUT_DIR})",
    )
    parser.add_argument(
        "--codec", choices=["h264", "h265", "jxsv"],
        help="Validate only a specific codec",
    )
    parser.add_argument(
        "--config", type=str,
        help="Validate only a specific config by name",
    )
    parser.add_argument("-v", "--verbose", action="store_true")
    parser.add_argument(
        "--full-report", action="store_true",
        help="Pass --full-report to validators (show all checks)",
    )
    args = parser.parse_args()

    configs = ALL_CONFIGS
    if args.codec:
        configs = [c for c in configs if c.codec == args.codec]
    if args.config:
        configs = [c for c in configs if c.name == args.config]
        if not configs:
            raise SystemExit(
                f"Unknown config '{args.config}'. "
                f"Available: {', '.join(c.name for c in ALL_CONFIGS)}"
            )

    if configs and not args.output_dir.exists():
        raise SystemExit(f"Output directory does not exist: {args.output_dir}")

    results: list[ValidationResult] = []
    total_checks = 0

    # --- Clear streams ---
    if configs:
        print("=" * 70)
        print("CLEAR STREAMS")
        print("=" * 70)
    for cfg in configs:
        codec_dir = args.output_dir / cfg.codec
        pcap = codec_dir / f"{cfg.name}.pcap"
        sdp = codec_dir / f"{cfg.name}.sdp"

        if not pcap.exists():
            print(f"  SKIP {cfg.name} — PCAP not found")
            results.append(ValidationResult(
                name=cfg.name, outcome=Outcome.SKIP,
            ))
            continue
        if not sdp.exists():
            print(f"  SKIP {cfg.name} — SDP not found")
            results.append(ValidationResult(
                name=cfg.name, outcome=Outcome.SKIP,
            ))
            continue

        r = validate_stream(
            pcap, sdp, cfg,
            encrypted=False, enc_flags=[],
            verbose=args.verbose, full_report=args.full_report,
        )
        results.append(r)
        checks = r.shall_pass + r.shall_fail + r.should_pass + r.should_fail
        total_checks += checks

        if r.outcome == Outcome.PASS:
            print(f"  PASS {cfg.name} "
                  f"(SHALL {r.shall_pass}/{r.shall_pass + r.shall_fail}, "
                  f"SHOULD {r.should_pass}/{r.should_pass + r.should_fail})")
        elif r.outcome == Outcome.FAIL:
            print(f"  FAIL {cfg.name} "
                  f"(SHALL {r.shall_pass}/{r.shall_pass + r.shall_fail}, "
                  f"SHOULD {r.should_pass}/{r.should_pass + r.should_fail})")
            if r.failures:
                for f in r.failures:
                    print(f"       {f}")
        elif r.outcome == Outcome.ERROR:
            print(f"  ERR  {cfg.name} — {r.error}")

    # --- Encrypted streams ---
    if configs:
        print()
        print("=" * 70)
        print("ENCRYPTED STREAMS")
        print("=" * 70)
    for cfg in configs:
        codec_dir = args.output_dir / cfg.codec
        for suffix, enc_flags in ENCRYPTION_SUFFIXES:
            enc_name = f"{cfg.name}{suffix}"
            pcap = codec_dir / f"{enc_name}.pcap"
            sdp = codec_dir / f"{enc_name}.sdp"

            if not pcap.exists():
                continue
            if not sdp.exists():
                print(f"  SKIP {enc_name} — SDP not found")
                results.append(ValidationResult(
                    name=enc_name, outcome=Outcome.SKIP,
                ))
                continue

            r = validate_stream(
                pcap, sdp, cfg,
                encrypted=True, enc_flags=enc_flags,
                verbose=args.verbose, full_report=args.full_report,
            )
            results.append(r)
            checks = r.shall_pass + r.shall_fail + r.should_pass + r.should_fail
            total_checks += checks

            if r.outcome == Outcome.PASS:
                print(f"  PASS {enc_name} "
                      f"(SHALL {r.shall_pass}/{r.shall_pass + r.shall_fail}, "
                      f"SHOULD {r.should_pass}/{r.should_pass + r.should_fail})")
            elif r.outcome == Outcome.FAIL:
                print(f"  FAIL {enc_name} "
                      f"(SHALL {r.shall_pass}/{r.shall_pass + r.shall_fail}, "
                      f"SHOULD {r.should_pass}/{r.should_pass + r.should_fail})")
                if r.failures:
                    for f in r.failures:
                        print(f"       {f}")
            elif r.outcome == Outcome.ERROR:
                print(f"  ERR  {enc_name} — {r.error}")

    # --- JXSV streams ---
    if args.codec is None or args.codec == "jxsv":
        print()
        print("=" * 70)
        print("JXSV STREAMS")
        print("=" * 70)
        if JXSV_STREAMS_DIR.exists():
            for jdef in JXSV_STREAMS:
                pcap = JXSV_STREAMS_DIR / f"{jdef.stem}.pcap"
                sdp = JXSV_STREAMS_DIR / f"{jdef.stem}.sdp"
                if not pcap.exists():
                    print(f"  SKIP {jdef.stem} — PCAP not found")
                    results.append(ValidationResult(
                        name=jdef.stem, outcome=Outcome.SKIP,
                    ))
                    continue
                if not sdp.exists():
                    print(f"  SKIP {jdef.stem} — SDP not found")
                    results.append(ValidationResult(
                        name=jdef.stem, outcome=Outcome.SKIP,
                    ))
                    continue

                r = validate_jxsv_stream(
                    pcap, sdp, jdef,
                    verbose=args.verbose, full_report=args.full_report,
                )
                results.append(r)
                checks = r.shall_pass + r.shall_fail + r.should_pass + r.should_fail
                total_checks += checks

                if r.outcome == Outcome.PASS:
                    print(f"  PASS {jdef.stem} "
                          f"(SHALL {r.shall_pass}/{r.shall_pass + r.shall_fail}, "
                          f"SHOULD {r.should_pass}/{r.should_pass + r.should_fail})")
                elif r.outcome == Outcome.FAIL:
                    print(f"  FAIL {jdef.stem} "
                          f"(SHALL {r.shall_pass}/{r.shall_pass + r.shall_fail}, "
                          f"SHOULD {r.should_pass}/{r.should_pass + r.should_fail})")
                    if r.failures:
                        for f in r.failures:
                            print(f"       {f}")
                elif r.outcome == Outcome.ERROR:
                    print(f"  ERR  {jdef.stem} — {r.error}")
        else:
            print(f"  SKIP — {JXSV_STREAMS_DIR} not found")

    # --- Summary ---
    passed = sum(1 for r in results if r.outcome == Outcome.PASS)
    failed = sum(1 for r in results if r.outcome == Outcome.FAIL)
    errors = sum(1 for r in results if r.outcome == Outcome.ERROR)
    skipped = sum(1 for r in results if r.outcome == Outcome.SKIP)

    print()
    print("=" * 70)
    print(f"SUMMARY: {passed} passed, {failed} failed, "
          f"{errors} errors, {skipped} skipped "
          f"({len(results)} streams, {total_checks} checks)")
    print("=" * 70)

    if failed > 0 or errors > 0:
        fail_results = [r for r in results if r.outcome in (Outcome.FAIL, Outcome.ERROR)]
        print("\nFailed/errored streams:")
        for r in fail_results:
            if r.outcome == Outcome.FAIL and r.failures:
                for f in r.failures:
                    print(f"  {r.name}: {f}")
            elif r.outcome == Outcome.ERROR:
                print(f"  {r.name}: ERROR — {r.error}")

    return 1 if (failed > 0 or errors > 0) else 0


if __name__ == "__main__":
    raise SystemExit(main())
