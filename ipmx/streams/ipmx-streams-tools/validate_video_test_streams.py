"""Validate all IPMX video test streams generated by generate_video_test_streams.py.

For each stream in test-streams/:
  - Clear streams: full validation with --hrd-timing (all 3 HRD tiers),
    --sdp cross-validation, and --allow-superset-profile.
  - Encrypted streams: validation with --sdp, --allow-superset-profile,
    and the appropriate --hkep / --pep flags.  HRD tiers are omitted
    because the payload is not accessible.

Run:
  python3 validate_video_test_streams.py [--output-dir DIR] [--codec h264|h265]
                                         [--config NAME] [--verbose] [--full-report]

Requires: the video test streams to have been generated first via
  python3 generate_video_test_streams.py
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from dataclasses import dataclass
from enum import Enum, auto
from pathlib import Path

from generate_video_test_streams import (
    ALL_CONFIGS,
    DEFAULT_OUTPUT_DIR,
    EncryptionMode,
    StreamConfig,
)


SCRIPT_DIR = Path(__file__).resolve().parent
JXSV_STREAMS_DIR = SCRIPT_DIR / "jxsv-streams"

ENCRYPTION_SUFFIXES: list[tuple[str, list[str]]] = [
    ("_hkep", ["--hkep"]),
    ("_pep", ["--pep"]),
    ("_hkep_pep", ["--hkep", "--pep"]),
]

@dataclass
class JxsvStreamDef:
    """Definition of a manually curated JXSV test stream."""
    stem: str
    enc_flags: list[str]
    exactframerate: str | None = None


class Outcome(Enum):
    PASS = auto()
    FAIL = auto()
    ERROR = auto()
    SKIP = auto()


@dataclass
class ValidationResult:
    name: str
    outcome: Outcome
    shall_pass: int = 0
    shall_fail: int = 0
    shall_untestable: int = 0
    should_pass: int = 0
    should_fail: int = 0
    should_untestable: int = 0
    failures: list[str] | None = None
    error: str | None = None


def _parse_summary_line(line: str) -> tuple[int, int, int] | None:
    """Parse '52/52 passed, 0 failed, 23 cannot test' into (pass, fail, untestable)."""
    try:
        parts = line.strip().split(",")
        passed = int(parts[0].split("/")[0])
        failed = int(parts[1].strip().split()[0])
        untestable = int(parts[2].strip().split()[0]) if len(parts) >= 3 else 0
        return passed, failed, untestable
    except (IndexError, ValueError):
        return None


def validate_stream(
    pcap: Path,
    sdp: Path,
    cfg: StreamConfig,
    encrypted: bool,
    enc_flags: list[str],
    verbose: bool,
    full_report: bool,
) -> ValidationResult:
    """Run the appropriate validator on a single stream."""
    name = pcap.stem

    if cfg.codec == "h265":
        validator = SCRIPT_DIR / "ipmx_h265_validate_pcap.py"
    else:
        validator = SCRIPT_DIR / "ipmx_h264_validate_pcap.py"

    cmd: list[str] = [
        sys.executable, str(validator), str(pcap),
        "--exactframerate", cfg.exactframerate_arg,
        "--sdp", str(sdp),
        "--allow-superset-profile",
    ]

    if not encrypted:
        cmd.append("--hrd-timing")

    cmd.extend(enc_flags)

    if full_report:
        cmd.append("--full-report")

    try:
        proc = subprocess.run(
            cmd, capture_output=True, text=True, timeout=600,
        )
    except subprocess.TimeoutExpired:
        return ValidationResult(
            name=name, outcome=Outcome.ERROR,
            error="Validator timed out after 600s",
        )
    except Exception as exc:
        return ValidationResult(
            name=name, outcome=Outcome.ERROR,
            error=str(exc),
        )

    output = proc.stdout + proc.stderr

    if proc.returncode != 0 and "does not exist" in output:
        return ValidationResult(
            name=name, outcome=Outcome.ERROR,
            error=f"Validator error: {output.strip()[-200:]}",
        )

    result = ValidationResult(name=name, outcome=Outcome.PASS)

    fail_lines: list[str] = []
    for line in output.splitlines():
        stripped = line.strip()
        if stripped.startswith("SHALL requirements"):
            continue
        if stripped.startswith("SHOULD requirements"):
            continue

        summary = _parse_summary_line(stripped)
        if summary is not None:
            p, f, u = summary
            if result.shall_pass == 0 and result.should_pass == 0:
                result.shall_pass = p
                result.shall_fail = f
                result.shall_untestable = u
            else:
                result.should_pass = p
                result.should_fail = f
                result.should_untestable = u
            continue

        if stripped.startswith("FAIL "):
            fail_lines.append(stripped)

    if result.shall_fail > 0 or fail_lines:
        result.outcome = Outcome.FAIL
        result.failures = fail_lines

    if verbose and output.strip():
        for line in output.splitlines():
            print(f"    {line}")

    return result


JXSV_STREAMS: list[JxsvStreamDef] = [
    JxsvStreamDef(stem="jxsv_2160p60_rgb_8_clear", enc_flags=[],
                  exactframerate="60"),
    JxsvStreamDef(stem="jxsv_2160p60_444_8_hkep", enc_flags=["--hkep"],
                  exactframerate="60"),
    JxsvStreamDef(stem="jxsv_1080p5994_rgb_8_pep", enc_flags=["--pep"],
                  exactframerate="60000/1001"),
]


